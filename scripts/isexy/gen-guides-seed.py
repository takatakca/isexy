#!/usr/bin/env python3
"""Generate the seed section of supabase/isexy-migrations/0017_help_guides.sql.

Reads data/areas/quebec_areas.csv and data/areas/cuba_areas.csv and writes the
INSERT statements for isexy.guides (5 admin seats, one Director per region or
province, one District Manager per municipality or borough) between the two
marker lines in 0017. The output is deterministic: running the script again
on the same CSV files reproduces the section byte for byte.

  python3 scripts/isexy/gen-guides-seed.py           # rewrite the section in 0017
  python3 scripts/isexy/gen-guides-seed.py --check   # exit 1 if 0017 is out of date
  python3 scripts/isexy/gen-guides-seed.py --print   # print the section only

Every INSERT ends with ON CONFLICT DO NOTHING (unique keys: seat for admins,
country + area_kind + area_slug for area guides), so re-running the migration
never duplicates a guide nor overwrites an admin's edits.

Once 0017 is applied anywhere (isexy.schema_migrations records its SHA-256),
the file is immutable: new or renamed areas then go in a new migration.
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
QUEBEC_CSV = ROOT / "data" / "areas" / "quebec_areas.csv"
CUBA_CSV = ROOT / "data" / "areas" / "cuba_areas.csv"
MIGRATION = ROOT / "supabase" / "isexy-migrations" / "0017_help_guides.sql"

BEGIN = "-- >>> BEGIN guides seed (generated by scripts/isexy/gen-guides-seed.py from data/areas/*.csv; do not edit by hand)"
END = "-- <<< END guides seed"

ADMIN_SEATS = 5
COLUMNS = "(kind, country, area_kind, area_code, area_slug, area_name, parent_name, display_name, search_text, seat)"


def lit(value):
    """SQL literal: NULL, an integer, or a single-quoted string."""
    if value is None:
        return "NULL"
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def row(kind, country, area_kind, area_code, area_slug, area_name, parent_name, display_name, search_words, seat=None):
    # search_text is folded by the same SQL function the search uses
    # (isexy.guide_fold: accents stripped, lowercased, punctuation to spaces).
    search = "isexy.guide_fold(" + lit(" ".join(w for w in search_words if w)) + ")"
    values = [lit(kind), lit(country), lit(area_kind), lit(area_code), lit(area_slug), lit(area_name),
              lit(parent_name), lit(display_name), search, lit(seat)]
    return "  (" + ", ".join(values) + ")"


def insert(comment, rows):
    out = ["-- " + comment, "INSERT INTO isexy.guides " + COLUMNS + " VALUES"]
    out.append(",\n".join(rows))
    out.append("ON CONFLICT DO NOTHING;")
    return "\n".join(out)


def read_csv(path):
    with path.open(encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def placeholder(area_name):
    return "ISEXY · " + area_name


def build():
    quebec = read_csv(QUEBEC_CSV)
    cuba = read_csv(CUBA_CSV)

    regions = {r["code"]: r for r in quebec if r["kind"] == "region"}
    cities = {r["code"]: r for r in quebec if r["kind"] == "municipality"}

    admins = [row("admin", None, None, None, None, None, None, f"Admin ISEXY {n}", [f"Admin ISEXY {n}"], n)
              for n in range(1, ADMIN_SEATS + 1)]

    qc_directors = [
        row("director", "CA-QC", "region", r["code"], r["slug"], r["name"], "Québec",
            placeholder(r["name"]), [r["name"], "Québec"])
        for r in quebec if r["kind"] == "region"
    ]

    qc_managers = []
    for r in quebec:
        if r["kind"] == "municipality":
            region = regions[r["parent_code"]]["name"]
            qc_managers.append(row("district_manager", "CA-QC", "municipality", r["code"], r["slug"], r["name"],
                                   region, placeholder(r["name"]), [r["name"], region]))
    for r in quebec:
        if r["kind"] == "borough":
            city = cities[r["parent_code"]]
            region = regions[city["parent_code"]]["name"]
            # A borough's parent for display is its region; the city's name is
            # searchable too ("Montréal" finds Ville-Marie, "Lévis" Desjardins).
            qc_managers.append(row("district_manager", "CA-QC", "borough", r["code"], r["slug"], r["name"],
                                   region, placeholder(r["name"]), [r["name"], city["name"], region]))

    cu_directors = [
        row("director", "CU", "province", None, r["slug"], r["province"], "Cuba",
            placeholder(r["province"]), [r["province"], "Cuba"])
        for r in cuba if r["kind"] == "province"
    ]
    cu_managers = [
        row("district_manager", "CU", "municipality", None, r["slug"], r["municipality"], r["province"],
            placeholder(r["municipality"]), [r["municipality"], r["province"]])
        for r in cuba if r["kind"] == "municipality"
    ]

    counts = {
        "admin": len(admins),
        "director": len(qc_directors) + len(cu_directors),
        "district_manager": len(qc_managers) + len(cu_managers),
    }
    parts = [
        BEGIN,
        f"-- {counts['admin']} admins, {counts['director']} directors "
        f"({len(qc_directors)} Québec regions + {len(cu_directors)} Cuban provinces), "
        f"{counts['district_manager']} district managers "
        f"({len(qc_managers)} Québec municipalities and boroughs + {len(cu_managers)} Cuban municipalities).",
        insert(f"Admin seats 1-{ADMIN_SEATS}", admins),
        insert("Québec: one Director per administrative region (MAMH code 01-17)", qc_directors),
        insert("Québec: one District Manager per municipality (5-digit MAMH code), then per borough", qc_managers),
        insert("Cuba: one Director per province (15 provinces + Isla de la Juventud)", cu_directors),
        insert("Cuba: one District Manager per municipality", cu_managers),
        END,
    ]
    return "\n".join(parts), counts


def splice(text, section):
    start = text.find(BEGIN)
    end = text.find(END)
    if start < 0 or end < 0 or end < start:
        raise SystemExit(f"{MIGRATION}: seed markers not found")
    return text[:start] + section + text[end + len(END):]


def main(argv):
    section, counts = build()
    if "--print" in argv:
        sys.stdout.write(section + "\n")
        return 0
    text = MIGRATION.read_text(encoding="utf-8")
    updated = splice(text, section)
    if "--check" in argv:
        if updated != text:
            print(f"{MIGRATION.relative_to(ROOT)} is out of date: run scripts/isexy/gen-guides-seed.py", file=sys.stderr)
            return 1
        print(f"seed section up to date ({counts['admin']} admins, {counts['director']} directors, "
              f"{counts['district_manager']} district managers)")
        return 0
    if updated != text:
        MIGRATION.write_text(updated, encoding="utf-8", newline="\n")
        print(f"rewrote the seed section of {MIGRATION.relative_to(ROOT)}")
    else:
        print("seed section already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
