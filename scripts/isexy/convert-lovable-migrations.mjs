#!/usr/bin/env node
// One-time tool: turns the Lovable-era migrations (public schema) into the
// isexy-schema baseline that runs on TAKATAK V1. Kept for audit; re-running it
// regenerates supabase/isexy-migrations/0001_isexy_baseline.sql byte for byte.
//
//   git archive 7044b07 supabase/migrations | tar -x -C /tmp/lovable   # the Lovable files, from history
//   node scripts/isexy/convert-lovable-migrations.mjs /tmp/lovable/supabase/migrations
//
// What it changes:
//   public.<x>            -> isexy.<x>
//   search_path = public  -> search_path = isexy, extensions   (never public)
//   bucket ids            -> isexy-<bucket>   (storage is shared with V1)
//   storage policies      -> "isexy: <name>"  (policy names are per table)
//   realtime ADD TABLE    -> isexy._realtime_add('<table>')  (idempotent, skips FOR ALL TABLES)
//   CREATE EXTENSION      -> removed (database-wide; V1 owns its extensions)
//   realtime.messages     -> policies removed (shared with V1; ISEXY has no private channels)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const src = process.argv[2];
if (!src) {
  console.error("usage: convert-lovable-migrations.mjs <dir>");
  process.exit(1);
}
const out = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../../supabase/isexy-migrations/0001_isexy_baseline.sql");

const BUCKETS = ["profile-photos", "cuban-verifications", "ticket-attachments", "voice-greetings", "voice-replies"];

function convert(sql) {
  let s = sql;
  s = s.replace(/^\s*CREATE EXTENSION[^;]*;\s*$/gim, "-- (removed: CREATE EXTENSION is database-wide on V1)");
  // realtime.messages is shared with V1; a permissive policy there would open
  // V1's private channels. ISEXY uses no private channels, so drop these.
  s = s.replace(/DROP POLICY IF EXISTS "[^"]+" ON realtime\.messages;/g, "-- (removed: realtime.messages policy is shared with V1)");
  s = s.replace(/CREATE POLICY "[^"]+"\s+ON realtime\.messages[\s\S]*?\n\);/g, "-- (removed: realtime.messages policy is shared with V1)");
  // search_path in function definitions and SET statements
  s = s.replace(/search_path\s*(=|TO)\s*'public'/gi, "search_path = isexy, extensions");
  s = s.replace(/search_path\s*(=|TO)\s*public\s*,\s*auth\b/gi, "search_path = isexy, extensions, auth");
  s = s.replace(/search_path\s*(=|TO)\s*public\b/gi, "search_path = isexy, extensions");
  // catalog lookups by schema name
  s = s.replace(/(schemaname|table_schema|nspname)\s*=\s*'public'/gi, "$1 = 'isexy'");
  // qualified names
  s = s.replace(/\bpublic\./g, "isexy.");
  // realtime publication
  s = s.replace(/ALTER PUBLICATION supabase_realtime ADD TABLE isexy\.(\w+)\s*;/gi, "PERFORM_REALTIME_ADD('$1');");
  // storage: bucket ids and policy names
  for (const b of BUCKETS) s = s.replace(new RegExp(`'${b}'`, "g"), `'isexy-${b}'`);
  s = s.replace(/((?:CREATE|DROP) POLICY (?:IF EXISTS )?)"([^"]+)"(\s+ON\s+storage\.objects)/gi, (_m, a, name, b) => `${a}"isexy: ${name}"${b}`);
  return s;
}

const files = readdirSync(src).filter((f) => f.endsWith(".sql")).sort();
let body = "";
for (const f of files) {
  let s = convert(readFileSync(path.join(src, f), "utf8"));
  // realtime adds may sit inside DO blocks (plpgsql) or at top level (SQL)
  s = s.replace(/PERFORM_REALTIME_ADD\('(\w+)'\);/g, (_m, t, offset, whole) => {
    const before = whole.slice(0, offset);
    const inDo = (before.match(/\bDO\s+\$\$/gi) || []).length > (before.match(/END\s*;?\s*\$\$/gi) || []).length;
    return inDo ? `PERFORM isexy._realtime_add('${t}');` : `SELECT isexy._realtime_add('${t}');`;
  });
  body += `\n-- ============================================================\n-- from Lovable migration ${f}\n-- ============================================================\n${s.trimEnd()}\n;\n`;
}

const prologue = `-- ISEXY baseline on TAKATAK V1 (generated by scripts/isexy/convert-lovable-migrations.mjs
-- from the ${files.length} Lovable-era migrations). Everything lives in the isexy schema;
-- nothing here creates or changes objects in V1's public schema.

CREATE SCHEMA IF NOT EXISTS isexy;
SET LOCAL search_path = isexy, extensions;

-- Same access model Supabase gives the public schema: RLS decides, roles may try.
GRANT USAGE ON SCHEMA isexy TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA isexy GRANT ALL ON TABLES TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA isexy GRANT ALL ON SEQUENCES TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA isexy GRANT EXECUTE ON FUNCTIONS TO anon, authenticated, service_role;

-- Realtime: add one isexy table to the shared publication, idempotently.
CREATE OR REPLACE FUNCTION isexy._realtime_add(p_table text) RETURNS void
LANGUAGE plpgsql SET search_path = isexy, pg_catalog AS $fn$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime') THEN
    RAISE NOTICE 'publication supabase_realtime missing; skipping %', p_table;
  ELSIF EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime' AND puballtables) THEN
    NULL; -- already publishes every table
  ELSIF NOT EXISTS (SELECT 1 FROM pg_publication_tables WHERE pubname = 'supabase_realtime' AND schemaname = 'isexy' AND tablename = p_table) THEN
    EXECUTE format('ALTER PUBLICATION supabase_realtime ADD TABLE isexy.%I', p_table);
  END IF;
END;
$fn$;
REVOKE ALL ON FUNCTION isexy._realtime_add(text) FROM PUBLIC, anon, authenticated;
`;

writeFileSync(out, prologue + body);
console.log(`wrote ${path.relative(process.cwd(), out)} from ${files.length} migrations`);
